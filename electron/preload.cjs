const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  github: {
    login: (token) => ipcRenderer.invoke('github:login', token),
    restoreSession: () => ipcRenderer.invoke('github:restore-session'),
    logout: () => ipcRenderer.invoke('github:logout'),
    getRepos: () => ipcRenderer.invoke('github:repos'),
    getLatestCommit: (owner, repo) => ipcRenderer.invoke('github:latest-commit', { owner, repo }),
    getCommitDetail: (owner, repo, sha) => ipcRenderer.invoke('github:commit-detail', { owner, repo, sha }),
    getRepository: (owner, repo, commitLimit) => ipcRenderer.invoke('github:repository', { owner, repo, commitLimit }),
    getCollaborators: (owner, repo) => ipcRenderer.invoke('github:collaborators', { owner, repo }),
    getInvitations: (owner, repo) => ipcRenderer.invoke('github:invitations', { owner, repo }),
    getContributors: (owner, repo) => ipcRenderer.invoke('github:contributors', { owner, repo }),
    getContributorStats: (owner, repo) => ipcRenderer.invoke('github:contributor-stats', { owner, repo }),
    getContributorTimeline: (owner, repo, login) => ipcRenderer.invoke('github:contributor-timeline', { owner, repo, login }),
    getUserProfile: (login) => ipcRenderer.invoke('github:user-profile', login),
    addCollaborator: (owner, repo, login, permission) => ipcRenderer.invoke('github:add-collaborator', { owner, repo, login, permission }),
    updateCollaborator: (owner, repo, login, permission) => ipcRenderer.invoke('github:update-collaborator', { owner, repo, login, permission }),
    removeCollaborator: (owner, repo, login) => ipcRenderer.invoke('github:remove-collaborator', { owner, repo, login }),
    cancelInvitation: (owner, repo, invitationId) => ipcRenderer.invoke('github:cancel-invitation', { owner, repo, invitationId }),
    createRepo: (name, description, isPrivate, folderPath, options) =>
      ipcRenderer.invoke('github:create-repo', { name, description, private: isPrivate, folderPath, ...options }),
    deleteRepo: (owner, repo) => ipcRenderer.invoke('github:delete-repo', { owner, repo }),
    updateRepo: (owner, repo, data) => ipcRenderer.invoke('github:update-repo', { owner, repo, data }),
    createBranch: (owner, repo, name, fromSha) => ipcRenderer.invoke('github:create-branch', { owner, repo, name, fromSha }),
    deleteBranch: (owner, repo, branch) => ipcRenderer.invoke('github:delete-branch', { owner, repo, branch }),
    renameBranch: (owner, repo, branch, newName) => ipcRenderer.invoke('github:rename-branch', { owner, repo, branch, newName }),
    getPullRequests: (owner, repo, state) => ipcRenderer.invoke('github:pull-requests', { owner, repo, state }),
    getPullRequest: (owner, repo, number) => ipcRenderer.invoke('github:pull-request', { owner, repo, number }),
    getPullRequestFiles: (owner, repo, number) => ipcRenderer.invoke('github:pull-request-files', { owner, repo, number }),
    approvePullRequest: (owner, repo, number) => ipcRenderer.invoke('github:approve-pull-request', { owner, repo, number }),
    mergePullRequest: (owner, repo, number, sha) => ipcRenderer.invoke('github:merge-pull-request', { owner, repo, number, sha }),
    updatePullRequestState: (owner, repo, number, state) => ipcRenderer.invoke('github:update-pull-request-state', { owner, repo, number, state }),
    createPullRequest: (owner, repo, title, body, head, base) => ipcRenderer.invoke('github:create-pull-request', { owner, repo, title, body, head, base }),
    getIssues: (owner, repo, state) => ipcRenderer.invoke('github:issues', { owner, repo, state }),
    getIssue: (owner, repo, number) => ipcRenderer.invoke('github:issue', { owner, repo, number }),
    createIssue: (owner, repo, title, body, labels) => ipcRenderer.invoke('github:create-issue', { owner, repo, title, body, labels }),
    searchCommits: (owner, repo, query, author, since, until) => ipcRenderer.invoke('github:search-commits', { owner, repo, query, author, since, until }),
    createRelease: (owner, repo, input) => ipcRenderer.invoke('github:create-release', { owner, repo, input }),
    getReadme: (owner, repo, branch) => ipcRenderer.invoke('github:get-readme', { owner, repo, branch }),
    saveReadme: (owner, repo, branch, content, message) => ipcRenderer.invoke('github:save-readme', { owner, repo, branch, content, message }),
    checkFolderChanges: (owner, repo, branch, folderPath) => ipcRenderer.invoke('github:check-folder-changes', { owner, repo, branch, folderPath }),
    commitFolderChanges: (owner, repo, branch, folderPath, message) => ipcRenderer.invoke('github:commit-folder-changes', { owner, repo, branch, folderPath, message }),
    checkGitFolderChanges: (folderPath, targetBranch) => ipcRenderer.invoke('git:check-folder-changes', { folderPath, targetBranch }),
    commitGitFolderChanges: (folderPath, targetBranch, message, push) => ipcRenderer.invoke('git:commit-folder-changes', { folderPath, targetBranch, message, push }),
  },
  app: {
    copyText: (text) => ipcRenderer.invoke('app:copy-text', text),
    getCurrentVersion: () => ipcRenderer.invoke('app:get-current-version'),
    getReleases: () => ipcRenderer.invoke('app:get-releases'),
    downloadRelease: (url, fileName, options) => ipcRenderer.invoke('app:download-release', { url, fileName, options }),
    downloadArchive: (owner, repo, sha, options) => ipcRenderer.invoke('app:download-archive', { owner, repo, sha, options }),
    selectUploadFolder: () => ipcRenderer.invoke('app:select-upload-folder'),
    selectReleaseAsset: () => ipcRenderer.invoke('app:select-release-asset'),
    selectDownloadFolder: () => ipcRenderer.invoke('app:select-download-folder'),
    clearUploadFolder: () => ipcRenderer.invoke('app:clear-upload-folder'),
    getAiStatus: () => ipcRenderer.invoke('ai:get-status'),
    runAiDiagnostics: (owner, repo, sha) => ipcRenderer.invoke('ai:diagnostics', { owner, repo, sha }),
    configureAiClient: (client) => ipcRenderer.invoke('ai:configure-client', { client }),
    disconnectAiClient: (client) => ipcRenderer.invoke('ai:disconnect-client', { client }),
    restartMcp: () => ipcRenderer.invoke('ai:restart-mcp'),
    allowMcpWrites: options => ipcRenderer.invoke('ai:allow-mcp-writes', options),
    revokeMcpWrites: () => ipcRenderer.invoke('ai:revoke-mcp-writes'),
    openAiConfigFolder: (client) => ipcRenderer.invoke('ai:open-config-folder', { client }),
  },
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
});
